"""Robustness table and macros for paper 1: primary split, V=60, swapped halves, bootstrap, uncertainty decomposition."""
import numpy as np, pandas as pd
import os; P = os.environ.get("OUT", "out").rstrip("/") + "/"; [os.makedirs(P + d, exist_ok=True) for d in ("tables", "figures")]
def pool(S, nm):
    y = S[nm].values; se = ((S[nm + "_hi"] - S[nm + "_lo"]) / (2 * 2.045)).values ** 2 + 1e-9
    wf = 1 / se; mu = (wf * y).sum() / wf.sum(); Q = (wf * (y - mu) ** 2).sum(); t2 = max(0, (Q - (len(y) - 1)) / (wf.sum() - (wf ** 2).sum() / wf.sum())); wr = 1 / (se + t2); mr = (wr * y).sum() / wr.sum(); s = np.sqrt(1 / wr.sum())
    return mr, mr - 1.96 * s, mr + 1.96 * s
def fmt(t): 
    f = lambda v: ("\\textminus{}" if v < 0 else "+") + f"{abs(v):.0f}"
    return f"{f(t[0])} [{f(t[1])}, {f(t[2])}]"
V = {"Primary (V=20, calibration = first half)": ("fin", 20), "More selection episodes (V=60)": ("fin", 60), "Halves swapped (V=20, calibration = second half)": ("finsw", 20)}
rows = []; mac = {}; base = {}
for lab, (tag, nv) in V.items():
    S = pd.read_csv(f"p1_{tag}{nv}_strategies.csv"); S = S[S.weights.str.startswith("paper")]; base[(tag, nv)] = S.set_index(["trace", "W"])
    b = pd.read_csv(f"p1_boot_{tag}{nv}.csv") if __import__("os").path.exists(f"p1_boot_{tag}{nv}.csv") else None
    r = dict(lab=lab, decpos=int(S["dec-simple_pos"].sum()), decneg=int(S["dec-simple_neg"].sum()), accpos=int(S["acc-simple_pos"].sum()), accneg=int(S["acc-simple_neg"].sum()),
             dpos=int(S["dec-acc_pos"].sum()), dneg=int(S["dec-acc_neg"].sum()), p_ds=pool(S, "dec-simple"), mean_ds=S["dec-simple"].mean(), med_ds=S["dec-simple"].median(), p_as=pool(S, "acc-simple"), p_da=pool(S, "dec-acc"),
             chd=None if b is None else b.p_dec_changes.median(), chs=None if b is None else b.p_simple_changes.median())
    rows.append(r)
k = {"fin20": 0, "fin60": 1, "finsw20": 2}
for key, i in k.items():
    r = rows[i]
    for f in ("decpos", "decneg", "accpos", "accneg", "dpos", "dneg"): mac[f"rob@{key}@{f}"] = r[f]
    for f in ("p_ds", "p_as", "p_da"): mac[f"rob@{key}@{f}"] = fmt(r[f])
    mac[f"rob@{key}@mean"] = fmt((r["mean_ds"],) * 3).split(" ")[0]; mac[f"rob@{key}@med"] = fmt((r["med_ds"],) * 3).split(" ")[0]
    if r["chd"] is not None: mac[f"rob@{key}@chd"] = f"{100*r['chd']:.0f}"; mac[f"rob@{key}@chs"] = f"{100*r['chs']:.0f}"
# swapped vs primary agreement
A = base[("fin", 20)]; B = base[("finsw", 20)]
mac["rob@same@dec"] = int((A.dec == B.dec).sum()); mac["rob@same@simple"] = int((A.simple == B.simple).sum()); mac["rob@same@acc"] = int((A.acc == B.acc).sum())
mac["rob@sign@agree"] = int((np.sign(A["dec-simple"]) == np.sign(B["dec-simple"])).sum())
mac["rob@split@sd"] = f"{(A['dec-simple'] - B['dec-simple']).abs().median():.0f}"
# uncertainty components (median over cells): test-episode CI half-width, bootstrap selection half-width, half-difference between splits
b20 = pd.read_csv("p1_boot_fin20.csv")
mac["unc@test"] = f"{b20.test_ci_halfwidth.median():.0f}"; mac["unc@boot"] = f"{((b20.boot_hi - b20.boot_lo) / 2).median():.0f}"; mac["unc@split"] = f"{((A['dec-simple'] - B['dec-simple']).abs() / 2).median():.0f}"
# minimum validation-segment length
with open(P + "tables/numbers_rob.tex", "w") as f:
    f.write("% generated by p1_extra.py\n\\makeatletter\n")
    for kk, v in mac.items(): f.write("\\expandafter\\def\\csname num@" + kk.replace("_", "@") + "\\endcsname{" + str(v) + "}\n")
    f.write("\\makeatother\n")
L = "\n".join(f"{r['lab']} & {r['decpos']} / {r['decneg']} & {r['accpos']} / {r['accneg']} & {fmt(r['p_ds'])} & {fmt((r['mean_ds'],)*3).split(' ')[0]} / {fmt((r['med_ds'],)*3).split(' ')[0]} & {fmt(r['p_da'])} & {'' if r['chd'] is None else str(round(100*r['chd']))+' / '+str(round(100*r['chs']))} \\\\" for r in rows)
open(P + "tables/tab_robsel.tex", "w").write("""\\begin{table*}[t]
\\centering
\\caption{Robustness of the selection comparison to the validation design (CloudSim Plus, 18 hosts, twelve cells, paper weights). Wins / losses count cells where the forecaster selection beats / loses to the validation-chosen simple rule with a 95\\% interval excluding zero. Pooled values are random-effects estimates of mean test return per 1000 tasks with 95\\% intervals; the mean and median columns are unweighted over the twelve cell differences. The last column gives the median over cells of the percentage of bootstrap resamples of the selection episodes in which the selected forecaster configuration / simple rule changes. The swapped run reuses the same test episodes and exchanges the roles of the two validation halves.}
\\label{tab:robsel}
\\scriptsize
\\resizebox{\\textwidth}{!}{%
\\begin{tabular}{@{}lrrrrrr@{}}
\\toprule
Design & Dec.\\ wins / losses & Acc.\\ wins / losses & Dec.\\ $-$ simple (pooled) & Dec.\\ $-$ simple (mean / median of cells) & Dec.\\ $-$ acc.\\ (pooled) & Selection changes (\\%) \\\\
\\midrule
""" + L + "\n\\bottomrule\n\\end{tabular}}\n\\end{table*}\n")
print(pd.DataFrame(rows).to_string()); print(mac)
